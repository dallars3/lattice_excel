CREATE TABLE IF NOT EXISTS `excel_bus_outbox` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `event_id` VARCHAR(64) NOT NULL,
  `type` VARCHAR(128) NOT NULL,
  `version` INT NOT NULL,
  `base_id` VARCHAR(64) NOT NULL DEFAULT '',
  `seq` BIGINT NOT NULL DEFAULT 0,
  `payload` JSON NOT NULL,
  `status` ENUM('sent', 'acked', 'dead') NOT NULL DEFAULT 'sent',
  `occurred_at` DATETIME(3) NOT NULL,
  `producer` VARCHAR(128) NOT NULL,
  `publish_attempts` INT UNSIGNED NOT NULL DEFAULT 0,
  `consume_attempts` INT UNSIGNED NOT NULL DEFAULT 0,
  `next_publish_at` DATETIME(3) NULL,
  `next_consume_at` DATETIME(3) NULL,
  `published_at` DATETIME(3) NULL,
  `acked_at` DATETIME(3) NULL,
  `dead_at` DATETIME(3) NULL,
  `last_error` VARCHAR(1024) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY `uk_excel_bus_outbox_event_id` (`event_id`),
  KEY `idx_excel_bus_outbox_forward` (`status`, `published_at`, `next_publish_at`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
